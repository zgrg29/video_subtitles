def set_language(language: str) -> None:
    global _current_language
    _current_language = language if language in UI_LANGUAGES else DEFAULT_UI_LANGUAGE


def get_language() -> str:
    return _current_language


def tr(key: str, **values: object) -> str:
    table = _STRINGS.get(_current_language, {})
    text = table.get(key) or _STRINGS["en"].get(key) or _STRINGS["zh"].get(key) or key
    if values:
        try:
            return text.format(**values)
        except (KeyError, ValueError):
            return text
    return text


def ui_language_label(code: str) -> str:
    return UI_LANGUAGE_LABELS.get(code, UI_LANGUAGE_LABELS["zh"])
